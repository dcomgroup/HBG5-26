const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const src=fs.readFileSync("shared/cloud-transport.js","utf8");
const window={};
vm.runInNewContext(src,{window,globalThis:window,URLSearchParams});
const api=window.HBG_CLOUD_TRANSPORT;
assert.equal(api.credentials("?p=panda-7a683212","",null).slug,"panda-7a683212");
assert.equal(api.credentials("?p=panda-7a683212","#sync=ignored",null).slug,"panda-7a683212");
assert.equal(api.credentials("?p=../evil","",null),null);
assert.equal(api.credentials("?p=panda-7a683212x".replace("x",""),"",null).slug,"panda-7a683212");
assert.equal(api.credentials("?p=other-profile","",null).slug,"other-profile");
assert.equal(api.credentials("?p=bad_slug","",null),null);
const calls=[];
const client=api.createClient({slug:"panda-7a683212"},async(url,options)=>{calls.push({url,options});return{ok:true,json:async()=>[]};});
(async()=>{
 await client.read("englisch-klassenarbeit-01");
 assert.match(calls[0].url,/hbg_read_events$/);
 const read=JSON.parse(calls[0].options.body);
 assert.equal(read.p_slug,"panda-7a683212");
 assert.equal(read.p_app_id,"englisch-klassenarbeit-01");
 assert.equal(Object.hasOwn(read,"p_secret"),false);
 await client.append({id:"11111111-1111-4111-8111-111111111111",appId:"englisch-klassenarbeit-01",cardId:"u1-colours",data:{state:{right:1}},at:"2026-11-15T00:00:00Z"});
 assert.match(calls[1].url,/hbg_append_event$/);
 const write=JSON.parse(calls[1].options.body);
 assert.equal(write.p_slug,"panda-7a683212");
 assert.equal(write.p_app_id,"englisch-klassenarbeit-01");
 assert.equal(write.p_card_id,"u1-colours");
 assert.equal(Object.hasOwn(write,"p_secret"),false);
 assert.throws(()=>client.append({id:"invalid"}),/Invalid event id/);
 console.log("PASS: URL-only profile access and learning-event RPC payloads");
})().catch(e=>{console.error(e);process.exitCode=1});