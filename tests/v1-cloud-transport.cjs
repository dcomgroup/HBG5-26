const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const src=fs.readFileSync("shared/cloud-transport.js","utf8");
const storage=new Map();
const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
const window={};
vm.runInNewContext(src,{window,globalThis:window});
const api=window.HBG_CLOUD_TRANSPORT;
const secret="a".repeat(64);
assert.equal(api.credentials("?p=panda-7a683212","",localStorage),null);
assert.equal(api.credentials("?p=../evil","#sync="+secret,localStorage),null);
assert.equal(api.credentials("?p=panda-7a683212","#sync=wrong",localStorage),null);
const creds=api.credentials("?p=panda-7a683212","#sync="+secret,localStorage);
assert.equal(creds.slug,"panda-7a683212");
assert.equal(creds.secret,secret);
assert.equal(api.credentials("?p=panda-7a683212","",localStorage).secret,secret);
assert.equal(api.credentials("?p=other-profile","",localStorage),null);
const calls=[];
const client=api.createClient(creds,async (url,options)=>{calls.push({url,options});return{ok:true,json:async()=>[]};});
(async()=>{
 await client.read("mathe");
 assert.match(calls[0].url,/read_learning_events$/);
 const payload=JSON.parse(calls[0].options.body);
 assert.equal(payload.p_slug,"panda-7a683212");
 assert.equal(payload.p_secret,secret);
 assert.equal(payload.p_app_id,"mathe");
 await client.append({id:"11111111-1111-4111-8111-111111111111",appId:"mathe",cardId:"1",data:{level:2},at:"2026-11-15T00:00:00Z"});
 assert.match(calls[1].url,/append_learning_event$/);
 assert.equal(JSON.parse(calls[1].options.body).p_card_id,"1");
 await assert.rejects(()=>client.append({id:"invalid"}),/Invalid event id/);
 console.log("PASS: cloud transport profile isolation, credentials and RPC payloads");
})().catch(e=>{console.error(e);process.exitCode=1});
